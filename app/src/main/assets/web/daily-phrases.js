export const dailyBackgrounds=['misty-lake','amber-hills','moonlit-peaks','quiet-coast','pine-valley','rose-dawn','summer-fields','blue-islands'];

export function dailyPhraseFor(date=new Date()) {
    const year=date.getFullYear(),month=date.getMonth(),day=date.getDate();
    const dayNumber=Math.floor(Date.UTC(year,month,day)/86400000);
    const index=((dayNumber%phrases.length)+phrases.length)%phrases.length;
    return {...phrases[index],background:dailyBackgrounds[((dayNumber%dailyBackgrounds.length)+dailyBackgrounds.length)%dailyBackgrounds.length],key:`${year}-${String(month+1).padStart(2,'0')}-${String(day).padStart(2,'0')}`,index};
}
export function nextPhraseUpdate(date=new Date()) {
    return Math.max(1,new Date(date.getFullYear(),date.getMonth(),date.getDate()+1).getTime()-date.getTime());
}
